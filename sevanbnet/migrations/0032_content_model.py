def _words(text):
    return " ".join(re.sub(r"[^a-z0-9]+", " ", (text or "").lower()).split())


def _unique_slug(model, title, taken):
    base = slugify(title)[:90] or "untitled"
    slug, n = base, 2
    while slug in taken or model.objects.filter(slug=slug).exists():
        slug, n = f"{base}-{n}", n + 1
    taken.add(slug)
    return slug


def _fill(obj, values):
    """Set each value only where the field is still empty."""
    for field, value in values.items():
        if getattr(obj, field) in (None, ""):
            setattr(obj, field, value)


def _media_from_img(img):
    """What the frontend made of a project's old `img` when it had no notes for it."""
    img = (img or "").strip()
    youtube = re.search(r"youtube(?:-nocookie)?\.com/embed/([\w-]{6,})", img)
    if youtube:
        return {"media_kind": "youtube", "media": f"https://www.youtube.com/watch?v={youtube[1]}"}
    if re.search(r"\.mp4$", img, re.I):
        return {"media_kind": "video", "media": img}
    return {"media_kind": "image", "media": img} if img else {}


def _project_slug(link, QRRedirect, follow=True):
    """The slug of the on-site project page a link points to, if it points to one."""
    link = (link or "").strip()
    if not link:
        return None
    parts = urlsplit(link)
    host, path = (parts.hostname or "").lower(), parts.path.rstrip("/")
    if host == "go.sevanb.net" and path.startswith("/r/"):
        code = path[3:]
        qr = QRRedirect.objects.filter(short_code=code).first()
        if qr and follow:
            return _project_slug(qr.target_url, QRRedirect, follow=False)
        return None if qr else LEGACY_SHORT_LINKS.get(code)
    if host not in SITE_HOSTS:
        return None
    if path in LEGACY_PATHS:
        return LEGACY_PATHS[path]
    match = re.fullmatch(r"/projects/([\w-]+)", path)
    return match[1] if match else None


def _paper_link(url, doi):
    url, doi = (url or "").strip(), (doi or "").strip()
    if url:
        return SITE_URL + url if url.startswith("/") else url
    if not doi:
        return ""
    if doi.startswith("http"):
        return doi
    if doi.lower().startswith("arxiv."):
        doi = "10.48550/" + doi
    return f"https://doi.org/{doi}"


def forward(apps, schema_editor):
    Project = apps.get_model("sevanbnet", "Project")
    Publication = apps.get_model("sevanbnet", "Publication")
    BlogPost = apps.get_model("sevanbnet", "BlogPost")
    QRRedirect = apps.get_model("sevanbnet", "QRRedirect")
    SiteSettings = apps.get_model("sevanbnet", "SiteSettings")

    SiteSettings.objects.get_or_create(pk=1, defaults=SITE_SETTINGS)

    # Projects
    for model in (Project, BlogPost):
        taken = set()
        for obj in model.objects.filter(models.Q(slug__isnull=True) | models.Q(slug="")):
            obj.slug = _unique_slug(model, obj.title, taken)
            obj.save(update_fields=["slug"])

    for project in Project.objects.all():
        extras = PROJECT_EXTRAS.get(project.slug)
        if extras is None:
            img = (project.img or "").strip()
            extras = _media_from_img(img)
            if re.search(r"\.(png|jpe?g|webp|gif|avif)$", img, re.I):
                extras["thumbnail"] = img
        _fill(project, extras)
        project.save()

    for slug, values in FLAGSHIPS.items():
        project = Project.objects.filter(slug=slug).first()
        if project is None:
            Project.objects.create(slug=slug, visible=True, listed=True, independent=True, **values)
        else:
            _fill(project, values)
            project.save()

    # Papers
    projects = set(Project.objects.values_list("slug", flat=True))
    for paper in Publication.objects.all():
        when = paper.publication_date or paper.submission_date
        paper.date = when.astimezone(ADMIN_TZ).date() if when else None
        paper.paper_url = _paper_link(paper.url, paper.doi)
        paper.bibtex = (paper.bibtex or "").replace("\r\n", "\n").replace("\r", "\n").strip()

        site_path = (paper.site_path or "").strip()
        external = (paper.project_url or "").strip()
        external_slug = _project_slug(external, QRRedirect)
        candidates = [_project_slug(site_path, QRRedirect), external_slug]
        linked = next((s for s in candidates if s in projects), None)
        if linked:
            paper.project = Project.objects.get(slug=linked)
            if external and external_slug != linked:
                print(f"\n  {paper.title!r}: links to /projects/{linked}; dropped {external}")
            external = ""
        elif site_path and not external:
            external = SITE_URL + site_path if site_path.startswith("/") else site_path
        paper.project_url = external

        text = f"{paper.url or ''} {paper.doi or ''}"
        for key, arxiv, title in WIDGET_PAPERS:
            if arxiv in text or _words(paper.title).startswith(title):
                if not paper.key and not Publication.objects.filter(key=key).exists():
                    paper.key = key
                if key == "temporal" and not paper.bibtex:
                    paper.bibtex = TEMPORAL_BIBTEX
        paper.save()

    # Text columns become NOT NULL in step 4; Django won't fill existing NULLs itself.
    for model, fields in [
        (Project, ["source", "description"]),
        (Publication, ["venue", "authors", "doi", "project_url", "description"]),
        (BlogPost, ["description"]),
    ]:
        for field in fields:
            model.objects.filter(**{f"{field}__isnull": True}).update(**{field: ""})

    if schema_editor.connection.vendor == "postgresql":
        # Fire the deferred foreign-key checks now, so the same transaction can alter tables.
        schema_editor.execute("SET CONSTRAINTS ALL IMMEDIATE")


def backward(apps, schema_editor):
    """Put values back into the old columns. Topics, associations and post text are gone,
    so this is for rehearsals only: production is rolled back by restoring the backup taken
    before the migration (docs/control-panel.md)."""
    Project = apps.get_model("sevanbnet", "Project")
    Publication = apps.get_model("sevanbnet", "Publication")

    for project in Project.objects.all():
        if project.media_kind == "youtube":
            video = re.search(r"([\w-]{11})$", project.media.split("v=")[-1])
            project.img = f"https://www.youtube.com/embed/{video[1] if video else ''}?mute=1&hd=1"
        elif project.media_kind in ("image", "video"):
            project.img = project.media
        project.save()

    for paper in Publication.objects.select_related("project"):
        if paper.date:
            when = datetime.combine(paper.date, time(), ADMIN_TZ)
            if re.search(r"accept|publish", paper.status, re.I):
                paper.publication_date = when
            else:
                paper.submission_date = when
        paper.url = paper.paper_url
        if paper.project:
            paper.project_url = f"{SITE_URL}/projects/{paper.project.slug}"
        paper.first_author = paper.authors.startswith("Sevan Brodjian")
        paper.save()

    # The old site hardcodes these two pages, so as rows they'd be listed twice. forward()
    # creates them, so they go again (the papers above already keep their links as URLs).
    Project.objects.filter(slug__in=FLAGSHIPS).delete()

    if schema_editor.connection.vendor == "postgresql":
        schema_editor.execute("SET CONSTRAINTS ALL IMMEDIATE")


